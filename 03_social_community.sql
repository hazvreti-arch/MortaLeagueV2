    values(new.reviewed_by,'report_'||new.status,'report',new.id::text,'Hedef: '||new.target_type||':'||new.target_id::text||'; neden: '||new.reason);
  end if;
  return new;
end;
$$;
revoke all on function public.audit_mortaleague_report_resolution() from public;
