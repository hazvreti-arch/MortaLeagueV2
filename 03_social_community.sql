-- A suspended account cannot create new direct conversations, even through a direct RPC call.
create or replace function public.create_direct_conversation(target_user_id uuid)
returns uuid language plpgsql security definer set search_path = '' as $$
declare v_me uuid := auth.uid(); v_conversation_id uuid;
begin
  if v_me is null then raise exception 'Giriş yapman gerekiyor.' using errcode = '28000'; end if;
  if public.is_mortaleague_suspended() then raise exception 'Hesabın kısıtlandığı için mesajlaşamazsın.' using errcode = '42501'; end if;
  if target_user_id is null or target_user_id=v_me then raise exception 'Kendinle sohbet başlatamazsın.' using errcode = '22023'; end if;
  if not exists(select 1 from public.profiles p where p.id=target_user_id and not p.is_suspended) then
    raise exception 'Bu oyuncu bulunamadı veya hesabı kısıtlı.' using errcode = 'P0002';
  end if;
  if public.is_direct_message_blocked(target_user_id) then raise exception 'Bu oyuncuyla sohbet başlatılamıyor. Engelleme durumunu kontrol et.' using errcode = '42501'; end if;
  insert into public.dm_conversations as existing(user_one,user_two)
  values(least(v_me,target_user_id),greatest(v_me,target_user_id))
  on conflict(user_one,user_two) do update set last_message_at=existing.last_message_at
  returning id into v_conversation_id;
  return v_conversation_id;
end;
$$;
revoke all on function public.create_direct_conversation(uuid) from public;
grant execute on function public.create_direct_conversation(uuid) to authenticated;

-- Respect suspension for direct messages too; function used by the existing DM RPC.
create or replace function public.can_direct_message(target_user_id uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select auth.uid() is not null
    and target_user_id is not null
    and target_user_id <> auth.uid()
    and not public.is_mortaleague_suspended()
    and exists (select 1 from public.profiles p where p.id=target_user_id and not p.is_suspended)
    and not public.is_direct_message_blocked(target_user_id);
$$;
revoke all on function public.can_direct_message(uuid) from public;
grant execute on function public.can_direct_message(uuid) to authenticated;

drop policy if exists "Users send direct messages when unblocked" on public.dm_messages;
create policy "Users send direct messages when unblocked" on public.dm_messages for insert to authenticated
  with check (sender_id=auth.uid() and not public.is_mortaleague_suspended()
    and exists(select 1 from public.dm_conversations c
      where c.id=conversation_id and (c.user_one=auth.uid() or c.user_two=auth.uid())
      and not public.is_direct_message_blocked(case when c.user_one=auth.uid() then c.user_two else c.user_one end)
      and exists(select 1 from public.profiles recipient
        where recipient.id=case when c.user_one=auth.uid() then c.user_two else c.user_one end
          and not recipient.is_suspended)));

