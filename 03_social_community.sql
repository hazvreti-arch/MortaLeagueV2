-- A signed-in user's suspension status is sourced only from the protected profile column.
create or replace function public.is_mortaleague_suspended()
returns boolean language sql stable security definer set search_path = '' as $$
  select coalesce((select p.is_suspended from public.profiles p where p.id = auth.uid()), false);
$$;
revoke all on function public.is_mortaleague_suspended() from public;
grant execute on function public.is_mortaleague_suspended() to authenticated;

create or replace function public.admin_set_profile_suspension(target_profile_id uuid, should_suspend boolean)
returns boolean language plpgsql security definer set search_path = '' as $$
declare target_role text;
begin
  if auth.uid() is null or not public.is_mortaleague_admin() then
    raise exception 'Yönetici yetkisi gerekli.' using errcode = '42501';
  end if;
  if target_profile_id = auth.uid() then
    raise exception 'Kendi hesabını askıya alamazsın.' using errcode = '22023';
  end if;
  select role into target_role from public.profiles where id = target_profile_id for update;
  if target_role is null then raise exception 'Oyuncu bulunamadı.' using errcode = 'P0002'; end if;
  if target_role = 'admin' then raise exception 'Yönetici hesabı bu işlemle askıya alınamaz.' using errcode = '42501'; end if;
  update public.profiles set is_suspended = should_suspend where id = target_profile_id;
  insert into public.admin_audit_log(admin_id,action_type,target_type,target_id,details)
  values(auth.uid(),case when should_suspend then 'profile_suspended' else 'profile_unsuspended' end,'profile',target_profile_id::text,
    case when should_suspend then 'Hesap askıya alındı.' else 'Hesap kısıtlaması kaldırıldı.' end);
  return true;
end;
$$;
revoke all on function public.admin_set_profile_suspension(uuid,boolean) from public;
grant execute on function public.admin_set_profile_suspension(uuid,boolean) to authenticated;

