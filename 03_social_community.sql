-- Trusted notification insertion and badge awarding happen only inside database triggers.
create or replace function public.add_mortaleague_notification(
  target_user uuid, actor_user uuid, notification_kind text, notification_body text,
  related_post uuid default null, related_comment uuid default null
) returns void language plpgsql security definer set search_path = '' as $$
begin
  if target_user is null or (actor_user is not null and target_user = actor_user) then return; end if;
  insert into public.notifications(recipient_id,actor_id,kind,body,post_id,comment_id)
  values(target_user,actor_user,notification_kind,left(notification_body,240),related_post,related_comment);
end;
$$;
revoke all on function public.add_mortaleague_notification(uuid,uuid,text,text,uuid,uuid) from public;

create or replace function public.award_mortaleague_achievement(target_user uuid, achievement_key text)
returns void language plpgsql security definer set search_path = '' as $$
declare badge_name text; inserted_rows integer;
begin
  if target_user is null then return; end if;
  select name into badge_name from public.achievement_catalog where code=achievement_key;
  if badge_name is null then return; end if;
  insert into public.user_achievements(user_id,achievement_code) values(target_user,achievement_key) on conflict do nothing;
  get diagnostics inserted_rows = row_count;
  if inserted_rows > 0 then
    perform public.add_mortaleague_notification(target_user,null,'badge','Yeni rozet kazandın: '||badge_name,null,null);
  end if;
end;
$$;
revoke all on function public.award_mortaleague_achievement(uuid,text) from public;

create or replace function public.after_mortaleague_post_insert()
returns trigger language plpgsql security definer set search_path = '' as $$
declare post_count integer; follower record;
begin
  select count(*) into post_count from public.posts where author_id=new.author_id;
  if post_count >= 1 then perform public.award_mortaleague_achievement(new.author_id,'first_post'); end if;
  if post_count >= 10 then perform public.award_mortaleague_achievement(new.author_id,'ten_posts'); end if;
  for follower in select follower_id from public.user_follows where following_id=new.author_id loop
    perform public.add_mortaleague_notification(follower.follower_id,new.author_id,'new_post','takip ettiğin oyuncu yeni bir gönderi paylaştı.',new.id,null);
  end loop;
  return new;
end;
$$;
revoke all on function public.after_mortaleague_post_insert() from public;
drop trigger if exists social_post_after_insert on public.posts;
create trigger social_post_after_insert after insert on public.posts for each row execute function public.after_mortaleague_post_insert();

