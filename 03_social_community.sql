-- Direct messages also appear in the recipient's notification center.
create or replace function public.after_mortaleague_dm_insert()
returns trigger language plpgsql security definer set search_path = '' as $$
declare recipient uuid;
begin
  select case when c.user_one = new.sender_id then c.user_two else c.user_one end
    into recipient
    from public.dm_conversations c
   where c.id = new.conversation_id
     and (c.user_one = new.sender_id or c.user_two = new.sender_id);
  if recipient is not null then
    perform public.add_mortaleague_notification(recipient,new.sender_id,'message','sana özel mesaj gönderdi.',null,null);
  end if;
  return new;
end;
$$;
revoke all on function public.after_mortaleague_dm_insert() from public;
drop trigger if exists social_dm_after_insert on public.dm_messages;
create trigger social_dm_after_insert after insert on public.dm_messages for each row execute function public.after_mortaleague_dm_insert();

-- A new admin announcement notifies every other registered player.
create or replace function public.after_mortaleague_announcement_insert()
returns trigger language plpgsql security definer set search_path = '' as $$
declare recipient record;
begin
  for recipient in select p.id from public.profiles p where p.id is distinct from new.created_by loop
    perform public.add_mortaleague_notification(recipient.id,new.created_by,'announcement','Yeni duyuru: '||new.title,null,null);
  end loop;
  return new;
end;
$$;
