-- Reported direct messages are surfaced to admins only through these narrowly scoped RPCs.
create or replace function public.admin_get_reported_message(target_message_id uuid)
returns table(id uuid,sender_id uuid,body text,created_at timestamptz)
language plpgsql security definer set search_path = '' as $$
begin
  if auth.uid() is null or not public.is_mortaleague_admin() then
    raise exception 'Yönetici yetkisi gerekli.' using errcode = '42501';
  end if;
  return query select m.id,m.sender_id,m.body,m.created_at from public.dm_messages m where m.id=target_message_id;
end;
$$;
revoke all on function public.admin_get_reported_message(uuid) from public;
grant execute on function public.admin_get_reported_message(uuid) to authenticated;

create or replace function public.admin_remove_reported_message(target_message_id uuid)
returns boolean language plpgsql security definer set search_path = '' as $$
declare found_message boolean;
begin
  if auth.uid() is null or not public.is_mortaleague_admin() then
    raise exception 'Yönetici yetkisi gerekli.' using errcode = '42501';
  end if;
  delete from public.dm_messages where id=target_message_id;
  found_message := found;
  if found_message then
    insert into public.admin_audit_log(admin_id,action_type,target_type,target_id,details)
    values(auth.uid(),'message_removed','message',target_message_id::text,'Şikâyet edilen özel mesaj kaldırıldı.');
  end if;
  return found_message;
end;
$$;
revoke all on function public.admin_remove_reported_message(uuid) from public;
grant execute on function public.admin_remove_reported_message(uuid) to authenticated;

create or replace function public.audit_mortaleague_content_delete()
returns trigger language plpgsql security definer set search_path = '' as $$
declare target_text text;
begin
  if public.is_mortaleague_admin() then
    if tg_table_name='posts' then target_text:=left(old.content,120);
    else target_text:=left(old.content,120); end if;
    insert into public.admin_audit_log(admin_id,action_type,target_type,target_id,details)
    values(auth.uid(),case when tg_table_name='posts' then 'post_removed' else 'comment_removed' end,
      case when tg_table_name='posts' then 'post' else 'comment' end,old.id::text,target_text);
  end if;
  return old;
end;
$$;
revoke all on function public.audit_mortaleague_content_delete() from public;
drop trigger if exists audit_post_delete on public.posts;
create trigger audit_post_delete after delete on public.posts for each row execute function public.audit_mortaleague_content_delete();
drop trigger if exists audit_comment_delete on public.post_comments;
create trigger audit_comment_delete after delete on public.post_comments for each row execute function public.audit_mortaleague_content_delete();

create or replace function public.audit_mortaleague_report_resolution()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if new.status is distinct from old.status and new.reviewed_by is not null and public.is_mortaleague_admin() then
